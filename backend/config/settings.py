# ---------------------------------------------------------------- Database
# PostgreSQL is the default. Setting USE_SQLITE=1 is only meant for quick
# automated tests on machines without PostgreSQL.
DATABASE_URL = os.getenv("DATABASE_URL", "").strip()

if os.getenv("USE_SQLITE") == "1":
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }
elif DATABASE_URL:
    # Neon / any hosted PostgreSQL: postgresql://user:password@host/dbname?sslmode=require
    from urllib.parse import parse_qs, unquote, urlparse

    _url = urlparse(DATABASE_URL)
    _query = {k: v[0] for k, v in parse_qs(_url.query).items()}
    _options = {"sslmode": _query.get("sslmode", "require")}
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": _url.path.lstrip("/"),
            "USER": unquote(_url.username or ""),
            "PASSWORD": unquote(_url.password or ""),
            "HOST": _url.hostname,
            "PORT": str(_url.port or 5432),
            "OPTIONS": _options,
            "CONN_MAX_AGE": 60,
            "CONN_HEALTH_CHECKS": True,
        }
    }
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": os.getenv("DB_NAME", "airojgar_resume_checker"),
            "USER": os.getenv("DB_USER", "postgres"),
            "PASSWORD": os.getenv("DB_PASSWORD", "postgres"),
            "HOST": os.getenv("DB_HOST", "localhost"),
            "PORT": os.getenv("DB_PORT", "5432"),
        }
    }

